#!/usr/bin/env python3
"""Rebuild the CSV files and the generated tables in README.md from the two JSON files in data/.

Usage: python3 scripts/build.py          # rewrite data/*.csv and README.md tables
       python3 scripts/build.py --check  # exit 1 if they are out of date
"""
import csv, io, json, pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
official = json.loads((ROOT / "data/official-prices.json").read_text())
standard = json.loads((ROOT / "data/hopbase-standard-prices.json").read_text())
by_id = {m["id"]: m for m in official["models"]}
FIELDS = ["input", "cached_input", "output"]
START, END = "<!-- tables:start (generated by scripts/build.py, do not edit by hand) -->", "<!-- tables:end -->"


def money(v):
    """4 significant digits, trailing zeros dropped: 0.005882 -> $0.005882, 12.2 -> $12.2."""
    if v is None:
        return ""
    s = f"{float(f'{v:.4g}'):.10f}".rstrip("0").rstrip(".")
    return f"${s}"


def exact(v):
    """Standard prices are shown exactly as published, never re-rounded."""
    return f"${v}"


def saving(std, off):
    if not off:
        return ""
    pct = round((1 - std / off) * 100)
    return f"{pct}%" if pct > 0 else "0%"


def natural_desc(models):
    import re
    key = lambda m: [int(t) if t.isdigit() else t for t in re.split(r"(\d+)", m["id"].lower())]
    return sorted(models, key=key, reverse=True)


def families():
    order = []
    for m in official["models"]:
        if m["family"] not in order:
            order.append(m["family"])
    fixed = ["Anthropic Claude", "OpenAI GPT / Codex", "OpenAI Image", "Google Gemini", "xAI Grok", "DeepSeek", "Zhipu GLM",
             "Alibaba Qwen", "Tencent Hunyuan", "ByteDance Seedream", "ByteDance Seedance", "Kuaishou Kling", "Midjourney",
             "MiniMax", "Alibaba Wan / HappyHorse", "Other"]
    return [f for f in fixed if f in order] + [f for f in order if f not in fixed]


def long_context(o):
    lc = o.get("long_context")
    if not lc:
        return ""
    return f"above {round(lc['threshold'] / 1000)}K input: in ×{lc.get('input_multiplier', 1)}, out ×{lc.get('output_multiplier', 1)}"


def buckets(o):
    parts = []
    for key in ("video_tokens", "image", "call"):
        for name, v in (o.get(key) or {}).items():
            parts.append(f"`{name}` {money(v)}")
    return ", ".join(parts)


def tables():
    out = [START, "", "## HopBase standard price vs. official list price", ""]
    out.append(f"USD per 1M tokens. Standard prices effective {standard['effective_from']}; "
               f"official list prices as of {official['fetched_at'][:10]}.")
    out += ["", "| Model | Official list (in / cached / out) | HopBase standard (in / cached / out) | Saving (in / cached / out) | Key group | Notes |",
            "| --- | --- | --- | --- | --- | --- |"]
    for p in standard["prices"]:
        o = by_id[p["id"]]["official"]
        notes = list(p.get("notes", []))
        if "then" in p:
            t = p["then"]
            notes.insert(0, f"From {t['from']}: " + " / ".join(exact(t[f]) for f in FIELDS))
        out.append("| `{}` | {} | {} | {} | {} | {} |".format(
            p["id"], " / ".join(money(o.get(f)) for f in FIELDS), " / ".join(exact(p[f]) for f in FIELDS),
            " / ".join(saving(p[f], o.get(f)) for f in FIELDS), p["key_group"], ". ".join(notes)))
    out += ["", "## Official list prices by model family", "",
            f"Snapshot {official['fetched_at'][:10]}, USD. Bucket names (resolution, audio, reference input) are the billing "
            "buckets returned by the source endpoint."]
    for fam in families():
        models = natural_desc([m for m in official["models"] if m["family"] == fam])
        out += ["", f"### {fam}", ""]
        token = [m for m in models if m["official"].get("input") or m["official"].get("output")]
        other = [m for m in models if m not in token]
        if token:
            out += ["| Model | Input | Cached input | Output | Unit | Also |", "| --- | --- | --- | --- | --- | --- |"]
            for m in token:
                o = m["official"]
                also = "; ".join(x for x in (long_context(o), (buckets(o) + " per image") if o.get("image") else "") if x)
                out.append(f"| `{m['id']}` | {money(o.get('input'))} | {money(o.get('cached_input'))} | {money(o.get('output'))} | per {m['unit']} | {also} |")
        if other:
            if token:
                out.append("")
            out += ["| Model | Price by bucket | Unit |", "| --- | --- | --- |"]
            for m in other:
                out.append(f"| `{m['id']}` | {buckets(m['official'])} | per {m['unit']} |")
    out += ["", END]
    return "\n".join(out)


def official_csv():
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    w.writerow(["id", "name", "family", "category", "unit", "bucket", "input", "cached_input", "output",
                "long_context_threshold", "long_context_input_multiplier", "long_context_output_multiplier", "price"])
    for m in official["models"]:
        o = m["official"]
        lc = o.get("long_context") or {}
        base = [m["id"], m["name"], m["family"], m["category"], m["unit"]]
        if o.get("input") or o.get("output"):
            w.writerow(base + ["", o.get("input", ""), o.get("cached_input", ""), o.get("output", ""),
                               lc.get("threshold", ""), lc.get("input_multiplier", ""), lc.get("output_multiplier", ""), ""])
        for key in ("video_tokens", "image", "call"):
            for name, v in (o.get(key) or {}).items():
                unit = "image" if key == "image" else m["unit"]
                w.writerow([m["id"], m["name"], m["family"], m["category"], unit, name, "", "", "", "", "", "", v])
    return buf.getvalue()


def standard_csv():
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    w.writerow(["id", "key_group", "input", "cached_input", "output", "official_input", "official_cached_input", "official_output",
                "next_price_from", "next_input", "next_cached_input", "next_output", "notes"])
    for p in standard["prices"]:
        o = by_id[p["id"]]["official"]
        t = p.get("then", {})
        w.writerow([p["id"], p["key_group"], p["input"], p["cached_input"], p["output"], o.get("input", ""), o.get("cached_input", ""),
                    o.get("output", ""), t.get("from", ""), t.get("input", ""), t.get("cached_input", ""), t.get("output", ""),
                    " ".join(n + "." for n in p.get("notes", []))])
    return buf.getvalue()


def main():
    readme = (ROOT / "README.md").read_text()
    a, b = readme.index(START), readme.index(END) + len(END)
    want = {"README.md": readme[:a] + tables() + readme[b:], "data/official-prices.csv": official_csv(),
            "data/hopbase-standard-prices.csv": standard_csv()}
    stale = [p for p, text in want.items() if not (ROOT / p).exists() or (ROOT / p).read_text() != text]
    if "--check" in sys.argv:
        if stale:
            sys.exit("out of date: " + ", ".join(stale))
        print("up to date")
        return
    for p in stale:
        (ROOT / p).write_text(want[p])
    print("rewrote: " + (", ".join(stale) or "nothing"))


if __name__ == "__main__":
    main()
